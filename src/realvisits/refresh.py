"""Rebuild the cloud and hosting ranges, and the referrer-spam list, from public sources.

`build_ranges` keeps every range of a public IP-to-ASN dataset (iptoasn.com's ip2asn-v4) whose ASN is
in the curated policy (data/datacenter_asns.txt, or your own), and joins ranges that touch.
`write_nets` writes them as the "<lo> <hi> <label>" lines a Classifier reads. `merge_spam` adds a
public referrer-spam list (Matomo's) to the hosts you already have. Run it out of band, on a
schedule, never in a request:

    realvisits refresh --out /path/to/data            # then Classifier(data_dir="/path/to/data")
    realvisits refresh --out /path/to/data --spam     # also merge the public spam list
    realvisits refresh --out DIR --ip2asn ip2asn-v4.tsv --asns my_asns.txt
"""
from __future__ import annotations

import gzip
import io
import sys
import urllib.request
from datetime import date
from pathlib import Path
from typing import Callable, Optional

from realvisits import __version__
from realvisits.classify import DATA, ip_to_int, read_hosts

IP2ASN_URL = "https://iptoasn.com/data/ip2asn-v4.tsv.gz"
SPAM_URL = "https://raw.githubusercontent.com/matomo-org/referrer-spam-list/master/spammers.txt"
# iptoasn.com refuses urllib's default agent, so the fetch names itself
UA = f"realvisits/{__version__} (+https://github.com/drkostas/realvisits)"


def fetch(url: str, timeout: int = 120) -> bytes:
    with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": UA}), timeout=timeout) as r:
        return r.read()


def read_asns(path: Path) -> dict:
    """The policy: "<asn> <label>" per line, comments starting with #."""
    asns = {}
    for line in Path(path).read_text().splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            parts = line.split()
            asns[parts[0]] = parts[1] if len(parts) > 1 else ""
    return asns


def read_ip2asn(local: Optional[str] = None, get: Callable = fetch) -> list:
    """The dataset's lines, from a local TSV or downloaded (gzip)."""
    if local:
        return Path(local).read_text().splitlines()
    return gzip.GzipFile(fileobj=io.BytesIO(get(IP2ASN_URL))).read().decode().splitlines()


def build_ranges(lines: list, asns: dict) -> list:
    """(lo, hi, label) for every dataset range whose ASN is in `asns`, sorted, touching ranges joined."""
    ranges = []
    for line in lines:
        if not line:
            continue
        start, end, asn = line.split("\t")[:3]
        label = asns.get(asn)
        if label is not None:
            ranges.append((ip_to_int(start), ip_to_int(end), label))
    ranges.sort()
    merged = []
    for lo, hi, label in ranges:
        if merged and lo <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(merged[-1][1], hi), merged[-1][2])
        else:
            merged.append((lo, hi, label))
    return merged


def write_nets(path: Path, merged: list, asn_count: int) -> None:
    out = ["# Cloud and hosting IPv4 ranges, as integer lo hi plus a provider label.",
           "# Generated by realvisits refresh from datacenter_asns.txt. Do not edit by hand.",
           f"# generated {date.today().isoformat()}, {asn_count} ASNs, {len(merged)} ranges", ""]
    out += [f"{lo} {hi} {label}" for lo, hi, label in merged]
    Path(path).write_text("\n".join(out) + "\n")


def merge_spam(path: Path, seed: Path = DATA / "spam_referrers.txt", get: Callable = fetch) -> int:
    """Write `path` as the union of the public spam list and the hosts already there (or in `seed`
    when `path` does not exist yet), keeping the comment lines. Returns how many hosts it holds."""
    fetched = {h.strip().lower() for h in get(SPAM_URL).decode().splitlines() if h.strip() and not h.startswith("#")}
    base = Path(path) if Path(path).exists() else Path(seed)
    lines = base.read_text().splitlines() if base.exists() else []
    header = [ln for ln in lines if ln.startswith("#") or ln == ""]
    hosts = sorted(set(read_hosts(base)) | fetched)
    Path(path).write_text("\n".join(header + hosts) + "\n")
    return len(hosts)


def run(out: Path, asns_file: Path = DATA / "datacenter_asns.txt", ip2asn: Optional[str] = None,
        spam: bool = False, get: Callable = fetch, say=print) -> int:
    """Write datacenter_nets.txt (and with `spam`, spam_referrers.txt) into `out`. 0 when the ranges
    were written; a failed spam fetch is reported and leaves the shipped list in place."""
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    asns = read_asns(asns_file)
    merged = build_ranges(read_ip2asn(ip2asn, get), asns)
    if not merged:
        say("no ranges built: check the ASN list and the ip2asn source", file=sys.stderr)
        return 1
    write_nets(out / "datacenter_nets.txt", merged, len(asns))
    say(f"wrote {out / 'datacenter_nets.txt'}: {len(asns)} ASNs, {len(merged)} ranges")
    if spam:
        try:
            say(f"wrote {out / 'spam_referrers.txt'}: {merge_spam(out / 'spam_referrers.txt', get=get)} hosts")
        except Exception as e:  # noqa: BLE001 - a failed public-list fetch must not fail the refresh
            say(f"spam list refresh skipped: {e}", file=sys.stderr)
            dest = out / "spam_referrers.txt"
            if not dest.exists():
                dest.write_text((DATA / "spam_referrers.txt").read_text())
    return 0
